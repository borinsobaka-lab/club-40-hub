"use client";

import * as React from "react";
import * as AvatarPrimitive from "@radix-ui/react-avatar";
import { getSvgPath } from "figma-squircle";

import { cn } from "@/lib/utils";

type SquircleAvatarProps = React.ComponentPropsWithoutRef<typeof AvatarPrimitive.Root> & {
  /** Pixel size of the avatar (square). Defaults to 44. */
  size?: number;
  /** Corner radius in px. Defaults to ~24% of size. */
  cornerRadius?: number;
  /** 0..1 smoothing (Figma slider 0..100%). Defaults to 0.6 (Clubhouse-like). */
  cornerSmoothing?: number;
};

/**
 * Squircle (superellipse) avatar — Clubhouse/iOS-style continuous corners.
 * Uses an SVG path generated by figma-squircle as a CSS clip-path.
 */
const SquircleAvatar = React.forwardRef<
  React.ElementRef<typeof AvatarPrimitive.Root>,
  SquircleAvatarProps
>(({ className, style, size = 44, cornerRadius, cornerSmoothing = 0.6, ...props }, ref) => {
  const radius = cornerRadius ?? Math.round(size * 0.24);
  const path = React.useMemo(
    () =>
      getSvgPath({
        width: size,
        height: size,
        cornerRadius: radius,
        cornerSmoothing,
      }),
    [size, radius, cornerSmoothing],
  );

  return (
    <AvatarPrimitive.Root
      ref={ref}
      className={cn("relative flex shrink-0 overflow-hidden", className)}
      style={{
        width: size,
        height: size,
        clipPath: `path('${path}')`,
        WebkitClipPath: `path('${path}')`,
        ...style,
      }}
      {...props}
    />
  );
});
SquircleAvatar.displayName = "SquircleAvatar";

const SquircleAvatarImage = React.forwardRef<
  React.ElementRef<typeof AvatarPrimitive.Image>,
  React.ComponentPropsWithoutRef<typeof AvatarPrimitive.Image>
>(({ className, ...props }, ref) => (
  <AvatarPrimitive.Image
    ref={ref}
    className={cn("aspect-square h-full w-full object-cover", className)}
    {...props}
  />
));
SquircleAvatarImage.displayName = "SquircleAvatarImage";

const SquircleAvatarFallback = React.forwardRef<
  React.ElementRef<typeof AvatarPrimitive.Fallback>,
  React.ComponentPropsWithoutRef<typeof AvatarPrimitive.Fallback>
>(({ className, ...props }, ref) => (
  <AvatarPrimitive.Fallback
    ref={ref}
    className={cn("flex h-full w-full items-center justify-center bg-muted", className)}
    {...props}
  />
));
SquircleAvatarFallback.displayName = "SquircleAvatarFallback";

export { SquircleAvatar, SquircleAvatarImage, SquircleAvatarFallback };

/** Returns a CSS `clip-path: path(...)` value for a Clubhouse-style squircle. */
export function squircleClipPath(size: number, cornerRadius?: number, cornerSmoothing = 0.6) {
  const radius = cornerRadius ?? Math.round(size * 0.24);
  const path = getSvgPath({ width: size, height: size, cornerRadius: radius, cornerSmoothing });
  return `path('${path}')`;
}
