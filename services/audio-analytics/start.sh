#!/usr/bin/env bash
# Один контейнер — два процесса: API (uvicorn) и воркер разбора.
#
# Разделять их на два ресурса Coolify незачем: они делят том /data (аудио на
# диске), версию кода и переменные окружения, а нагрузка — одна-две смены в
# день. Если любой из процессов умер, скрипт завершается с ошибкой, и Docker
# перезапускает контейнер целиком: полуживой контейнер (API отвечает, а
# разбор молча стоит) хуже честного перезапуска. Смена, которую воркер не
# дорабатывал, при старте вернётся в очередь (app/worker.py).
#
# bash здесь — PID 1: сигналы сам он детям не передаёт, поэтому trap
# пересылает SIGTERM от «docker stop» обоим процессам.
set -u

python -m app.worker &
WORKER=$!

uvicorn app.main:app --host 0.0.0.0 --port "${PORT:-8000}" \
  --proxy-headers --forwarded-allow-ips='*' --no-server-header &
API=$!

stop() {
  kill -TERM "$API" "$WORKER" 2>/dev/null
}
trap stop TERM INT

# Ждём первого завершившегося; дальше гасим второго и выходим.
wait -n "$API" "$WORKER"
code=$?
stop
wait
# Процесс вышел «успешно» сам по себе — для сервиса это всё равно авария.
if [ "$code" -eq 0 ]; then
  code=1
fi
exit "$code"
